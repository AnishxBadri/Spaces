import { sql } from 'drizzle-orm'
import {
  check,
  index,
  integer,
  jsonb,
  pgTable,
  primaryKey,
  text,
  timestamp,
  uniqueIndex,
  uuid,
} from 'drizzle-orm/pg-core'
import { user } from './auth'
import { integration } from './integrations'
import { space } from './kinds'
import type { Json } from '../json'

/**
 * A watch's settings, as the plugin's per-watch settings schema accepted
 * them. Open at the column for the reason `integration.config` is: the
 * manifest knows the shape, this package does not.
 */
export type SpaceWatchSettings = { [k: string]: Json }

/** The plugin-owned cursor a watch resumes from (a webset id, a history id). */
export type SpaceWatchState = { [k: string]: Json }

/**
 * A saved research lens on a space: one integration, its settings, an
 * optional clock. Host state — the engine never knows the space table.
 * - `cadence_minutes` null: the watch runs only on "Run now".
 * - An archived space pauses its watches; the scheduler reads `space`, so
 *   no column here says so.
 * - The same lens is not saved twice: `settings_hash` is the md5 of the
 *   canonical jsonb text, generated by the database so no writer can
 *   disagree. md5, not sha256: a generated column must be IMMUTABLE, and
 *   `convert_to` (sha256's bytea door) is only STABLE.
 */
export const spaceWatch = pgTable(
  'space_watch',
  {
    id: uuid('id').primaryKey().defaultRandom(),
    spaceId: uuid('space_id')
      .notNull()
      .references(() => space.entityId),
    integrationId: uuid('integration_id')
      .notNull()
      .references(() => integration.id),
    settings: jsonb('settings').$type<SpaceWatchSettings>().notNull(),
    settingsHash: text('settings_hash')
      .notNull()
      .generatedAlwaysAs(sql`md5(settings::text)`),
    cadenceMinutes: integer('cadence_minutes'),
    state: jsonb('state').$type<SpaceWatchState>(),
    lastRunAt: timestamp('last_run_at', { withTimezone: true }),
    lastStatus: text('last_status'),
    lastError: text('last_error'),
    createdBy: text('created_by').references(() => user.id),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [
    uniqueIndex('space_watch_lens_unique').on(
      t.spaceId,
      t.integrationId,
      t.settingsHash,
    ),
    index('space_watch_integration_idx').on(t.integrationId),
    check(
      'space_watch_cadence_positive',
      sql`${t.cadenceMinutes} IS NULL OR ${t.cadenceMinutes} > 0`,
    ),
  ],
)

/**
 * "Not this one, not here": a domain dismissed from a space's discovery
 * cards. Permanent per (space, domain), and read before a card is made, so
 * a later proposal for the domain is a database no-op.
 * - `domain` is normalized (`normalizeDomain`) before it is written.
 */
export const spaceWatchDismissal = pgTable(
  'space_watch_dismissal',
  {
    spaceId: uuid('space_id')
      .notNull()
      .references(() => space.entityId),
    domain: text('domain').notNull(),
    dismissedBy: text('dismissed_by')
      .notNull()
      .references(() => user.id),
    createdAt: timestamp('created_at', { withTimezone: true })
      .notNull()
      .defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.spaceId, t.domain] })],
)
