const portsFor = (api: FakeDriveApi, accessToken = api.accessToken) =>
  Layer.merge(
    HttpFetchTest(api.fetch).layer,
    SecretsTest({ accessToken }).layer,
  )

const subject = (api: FakeDriveApi = makeFakeDriveApi()) => ({
  api,
  source: Effect.runSync(Effect.provide(driveSource, portsFor(api))),
})

const run = <TValue, TError>(effect: Effect.Effect<TValue, TError>) =>
  Effect.runPromise(effect)

/** The typed failure, or null when the effect succeeded. */
const failureTag = <TValue, TError>(effect: Effect.Effect<TValue, TError>) =>
  Effect.runPromise(
    Effect.match(effect, { onFailure: (e) => e, onSuccess: () => null }),
  )

const bytesOf = (stream: ReadableStream<Uint8Array>) =>
  Effect.promise(
    async () => new Uint8Array(await new Response(stream).arrayBuffer()),
  )

const requestsTo = (api: FakeDriveApi, path: string) =>
  api.requests.filter((r: DriveApiRequest) => r.path === path)

