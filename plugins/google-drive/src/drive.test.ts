describe('the list job', () => {
  it('walks the configured folder and logs every entry with its path', async () => {
    const api = makeFakeDriveApi()
    const log = LogTest()
    const exit = await Effect.runPromiseExit(
      jobs
        .list({ cursor: null })
        .pipe(
          Effect.provide(
            Layer.mergeAll(
              portsFor(api),
              ConfigTest({ folderId: 'dataroom' }).layer,
              log.layer,
            ),
          ),
        ),
    )
    expect(exit).toEqual(Exit.succeed({ nextCursor: null }))
    const paths = log.lines
      .filter((l) => l.message === 'entry')
      .map((l) => l.fields.path)
    expect(paths).toEqual([
      'My Drive/Acme Data Room/01 Legal',
      'My Drive/Acme Data Room/02 Finance',
      'My Drive/Acme Data Room/Acme deck.pdf',
      'My Drive/Acme Data Room/Cap table.xlsx',
      'My Drive/Acme Data Room/Investment memo',
      'My Drive/Acme Data Room/01 Legal/Share purchase agreement.pdf',
      'My Drive/Acme Data Room/02 Finance/Board',
      'My Drive/Acme Data Room/02 Finance/Board/Minutes Q3.pdf',
    ])
    expect(log.lines.at(-1)).toMatchObject({
      message: 'listed',
      fields: { entries: 8 },
    })
  })

  it('fails permanently on a folder the connection cannot see', async () => {
    const api = makeFakeDriveApi()
    const job = jobs
      .list({ cursor: null })
      .pipe(
        Effect.provide(
          Layer.mergeAll(
            portsFor(api),
            ConfigTest({ folderId: 'never-seeded' }).layer,
            LogTest().layer,
          ),
        ),
      )
    expect(await failureTag(job)).toMatchObject({
      _tag: 'JobPermanent',
    })
  })
})
