const folderCreates = (api: FakeDriveApi) =>
  api.requests.filter((r) => r.method === 'POST' && r.path === '/files')

const encoder = new TextEncoder()

const uploadOf = (bytes: Uint8Array, mime = 'application/pdf') =>
  Effect.map(sha256Hex(bytes), (sha256) => ({
    mime,
    sha256,
    stream: new Blob([bytes.slice()]).stream(),
  }))

describe('ensureFolder', () => {
  it('meets the duplicate-name trap and leaves one chain: racing creates resolve to the oldest, losers delete their own', async () => {
    const { api, source } = subject()
    const ids = await run(
      Effect.all(
        Array.from({ length: 4 }, () =>
          source.ensureFolder('root', 'Portfolio/Acme'),
        ),
        { concurrency: 'unbounded' },
      ),
    )
    expect(new Set(ids).size).toBe(1)
    // The trap was really there: more than one Portfolio was created.
    const creates = folderCreates(api).length
    expect(creates).toBeGreaterThan(2)
    const deletes = api.requests.filter((r) => r.method === 'DELETE').length
    expect(creates - deletes).toBe(2)
    expect(
      api.drive.tree('root').filter((p) => p.startsWith('Portfolio')),
    ).toEqual(['Portfolio', 'Portfolio/Acme'])
  })

  it('creates lazily: a path that exists costs no create', async () => {
    const { api, source } = subject()
    const id = await run(
      source.ensureFolder('root', 'Acme Data Room/02 Finance/Board'),
    )
    expect(id).toBe('board')
    expect(folderCreates(api)).toEqual([])
  })

  it('writes into a shared drive with supportsAllDrives', async () => {
    const { api, source } = subject()
    const id = await run(source.ensureFolder('sd-portfolio', 'Acme/Legal'))
    expect(api.drive.tree('sd-portfolio')).toContain('Acme/Legal')
    expect(api.drive.entry(id)?.parentId).toBe('sd-acme')
    for (const create of folderCreates(api))
      expect(create.query.supportsAllDrives).toBe('true')
  })

  it('finds a name with a quote in it', async () => {
    const { api, source } = subject()
    const first = await run(source.ensureFolder('root', "O'Brien \\ Co"))
    const again = await run(source.ensureFolder('root', "O'Brien \\ Co"))
    expect(again).toBe(first)
    expect(folderCreates(api)).toHaveLength(1)
  })

  it('a revoked token is AuthExpired, and nothing is created', async () => {
    const { api, source } = subject()
    api.drive.revoke()
    expect(await failureTag(source.ensureFolder('root', 'A'))).toMatchObject({
      _tag: 'AuthExpired',
    })
    expect(folderCreates(api)).toEqual([])
  })
})

describe('putFile', () => {
  const uploads = (api: FakeDriveApi) =>
    api.requests.filter((r) => r.upload && r.method === 'PUT')

  it.each([
    ['one byte past a chunk', UPLOAD_CHUNK_BYTES + 1, 2],
    ['exactly one chunk', UPLOAD_CHUNK_BYTES, 2],
    ['a small file', 1000, 1],
    ['an empty file', 0, 1],
  ])(
    'streams %s in resumable chunks and reads back the same bytes',
    async (_label, size, puts) => {
      const { api, source } = subject()
      const bytes = Uint8Array.from({ length: size }, (_, i) => (i * 31) % 251)
      const content = await run(uploadOf(bytes))
      const put = await run(source.putFile('legal', 'Scan.pdf', content))
      expect(uploads(api)).toHaveLength(puts)
      const file = await run(source.getFile(put.fileId))
      const back = await run(bytesOf(file.stream))
      expect(await run(sha256Hex(back))).toBe(content.sha256)
      expect(api.drive.revisions(put.fileId)).toEqual([put.revisionId])
    },
  )

  it('uploads a revision of the same-sha file in place, with no new file', async () => {
    const { api, source } = subject()
    const bytes = encoder.encode('%PDF-1.7 SPA')
    const put = await run(
      Effect.flatMap(uploadOf(bytes), (c) =>
        source.putFile('legal', 'Share purchase agreement.pdf', c),
      ),
    )
    // The seeded SPA holds these bytes: its revision, not a (2).
    expect(put).toMatchObject({
      fileId: 'spa',
      name: 'Share purchase agreement.pdf',
    })
    expect(api.drive.revisions('spa')).toHaveLength(2)
    const opened = api.requests.filter(
      (r) => r.upload && r.method === 'PATCH' && r.path === '/files/spa',
    )
    expect(opened).toHaveLength(1)
  })

  it('names the docx it uploads by its own mime, never a native one', async () => {
    const { api, source } = subject()
    const bytes = Uint8Array.from([0x50, 0x4b, 0x03, 0x04, 1, 2, 3])
    const put = await run(
      Effect.flatMap(uploadOf(bytes, DOCX_MIME), (c) =>
        source.putFile('dataroom', 'Memo.docx', c),
      ),
    )
    expect(api.drive.entry(put.fileId)?.mime).toBe(DOCX_MIME)
    const listed = (await run(source.listFolder('dataroom'))).entries.find(
      (e) => e.id === put.fileId,
    )
    expect(listed?.mime).toBe(DOCX_MIME)
  })
})

describe('move and rename', () => {
  it('move removes the old parent, and a replay sends nothing', async () => {
    const { api, source } = subject()
    await run(source.move('deck', 'legal'))
    const patches = () =>
      api.requests.filter((r) => r.method === 'PATCH' && !r.upload)
    expect(patches().map((r) => r.query)).toEqual([
      expect.objectContaining({
        addParents: 'legal',
        removeParents: 'dataroom',
      }),
    ])
    await run(source.move('deck', 'legal'))
    expect(patches()).toHaveLength(1)
    expect(api.drive.entry('deck')?.parentId).toBe('legal')
  })

  it('rename writes once, and a replay sends nothing', async () => {
    const { api, source } = subject()
    await run(source.rename('deck', 'Acme deck v2.pdf'))
    await run(source.rename('deck', 'Acme deck v2.pdf'))
    expect(
      api.requests.filter((r) => r.method === 'PATCH' && !r.upload),
    ).toHaveLength(1)
    expect(api.drive.entry('deck')?.name).toBe('Acme deck v2.pdf')
  })

  it('a move into a missing folder is NotFound naming it', async () => {
    const { source } = subject()
    expect(await failureTag(source.move('deck', 'nowhere'))).toMatchObject({
      _tag: 'NotFound',
      id: 'nowhere',
    })
  })
})

describe('getFile', () => {
  it('exports a Google Doc to docx, hashed from the exported bytes, with Drive’s version as the change token', async () => {
    const { api, source } = subject()
    const read = (s: StorageSource) =>
      Effect.gen(function* () {
        const file = yield* s.getFile('memo')
        const bytes = yield* bytesOf(file.stream)
        return { file, bytes, sha: yield* sha256Hex(bytes) }
      })
    const first = await run(read(source))
    const second = await run(read(source))

    expect(first.file.mime).toBe(DOCX_MIME)
    expect(first.file.name).toBe('Investment memo.docx')
    expect([...first.bytes.slice(0, 4)]).toEqual([0x50, 0x4b, 0x03, 0x04])
    // The same unchanged Doc: new bytes, the same change identity.
    expect(second.sha).not.toBe(first.sha)
    expect(second.file.changeToken).toBe(first.file.changeToken)
    const exports = requestsTo(api, '/files/memo/export')
    expect(exports).toHaveLength(2)
    expect(exports.at(0)?.query.mimeType).toBe(DOCX_MIME)
    expect(
      requestsTo(api, '/files/memo').map((r) => r.query.alt),
    ).not.toContain('media')

    // An edit is what moves the token.
    api.drive.edit('memo', 'Acme investment memo, revised.')
    const third = await run(read(source))
    expect(third.file.changeToken).not.toBe(first.file.changeToken)
  })

  it('streams any other file through alt=media, as its own mime and name', async () => {
    const { api, source } = subject()
    const file = await run(source.getFile('deck'))
    expect(file.mime).toBe('application/pdf')
    expect(file.name).toBe('Acme deck.pdf')
    // The folder it sits in, from the metadata call: no extra request.
    expect(file.parentId).toBe('dataroom')
    expect(
      requestsTo(api, '/files/deck').some((r) =>
        (r.query.fields ?? '').split(',').includes('parents'),
      ),
    ).toBe(true)
    const text = new TextDecoder().decode(await run(bytesOf(file.stream)))
    expect(text).toBe('%PDF-1.7 Acme seed deck')
    const media = requestsTo(api, '/files/deck').filter(
      (r) => r.query.alt === 'media',
    )
    expect(media).toHaveLength(1)
    expect(media.at(0)?.query.supportsAllDrives).toBe('true')
  })

  it('is NotFound for a folder, which has no bytes', async () => {
    const { source } = subject()
    expect(await failureTag(source.getFile('legal'))).toMatchObject({
      _tag: 'NotFound',
      id: 'legal',
    })
  })
})

describe('listFolder', () => {
  it('lists a shared drive’s folder with supportsAllDrives and includeItemsFromAllDrives', async () => {
    const { api, source } = subject()
    const page = await run(source.listFolder('sd-portfolio'))
    expect(page.entries.map((e) => e.id)).toEqual(['sd-acme'])
    const list = requestsTo(api, '/files').at(0)
    expect(list?.query).toMatchObject({
      q: "'sd-portfolio' in parents and trashed = false",
      supportsAllDrives: 'true',
      includeItemsFromAllDrives: 'true',
    })
  })

  it('pages with pageToken and pageSize', async () => {
    const { api, source } = subject()
    const first = await run(source.listFolder('dataroom', { pageSize: 2 }))
    expect(first.next).toBeDefined()
    await run(
      source.listFolder('dataroom', { pageSize: 2, cursor: first.next ?? '' }),
    )
    const pages = requestsTo(api, '/files')
    expect(pages.map((r) => r.query.pageSize)).toEqual(['2', '2'])
    expect(pages.at(0)?.query.pageToken).toBeUndefined()
    expect(pages.at(1)?.query.pageToken).toBe(first.next)
  })

  it('is CursorExpired for a page token Drive no longer honours', async () => {
    const { source } = subject()
    expect(
      await failureTag(source.listFolder('dataroom', { cursor: 'stale' })),
    ).toMatchObject({ _tag: 'CursorExpired', cursor: 'stale' })
  })
})

describe('changes', () => {
  it('reads a shared drive with driveId and both all-drives flags, and My Drive with neither driveId nor a widening corpora', async () => {
    const { api, source } = subject()
    const start = await run(source.changes(null))
    const starts = requestsTo(api, '/changes/startPageToken')
    expect(starts.map((r) => r.query.driveId)).toEqual([
      undefined,
      'sd-portfolio',
    ])

    api.drive.edit('deck', '%PDF-1.7 Acme seed deck, v2')
    api.drive.edit('sd-update', '%PDF-1.7 Q3 investor update, v2')
    const page = await run(source.changes(start.next))

    const lists = requestsTo(api, '/changes')
    const myDrive = lists.filter((r) => r.query.driveId === undefined)
    const shared = lists.filter((r) => r.query.driveId === 'sd-portfolio')
    expect(myDrive).toHaveLength(1)
    expect(shared).toHaveLength(1)
    for (const request of myDrive) {
      expect(request.query.corpora).toBeUndefined()
      expect(request.query.includeItemsFromAllDrives).toBeUndefined()
      expect(request.query.pageToken).toBeDefined()
    }
    expect(shared.at(0)?.query).toMatchObject({
      driveId: 'sd-portfolio',
      includeItemsFromAllDrives: 'true',
      supportsAllDrives: 'true',
    })

    expect(
      page.changes.map((c) => (c._tag === 'changed' ? c.entry.id : c.id)),
    ).toEqual(['deck', 'sd-update'])
    const deck = page.changes.at(0)
    expect(deck?._tag === 'changed' && deck.entry.parentId).toBe('dataroom')

    // Nothing since: the next cursor reads back empty.
    const quiet = await run(source.changes(page.next))
    expect(quiet.changes).toEqual([])
  })

  it('reports a removal as removed', async () => {
    const { api, source } = subject()
    const start = await run(source.changes(null))
    api.drive.remove('captable')
    const page = await run(source.changes(start.next))
    expect(page.changes).toEqual([{ _tag: 'removed', id: 'captable' }])
  })

  it('surfaces Drive’s 410 as CursorExpired', async () => {
    const { api, source } = subject()
    const start = await run(source.changes(null))
    api.drive.evictCursors()
    expect(await failureTag(source.changes(start.next))).toMatchObject({
      _tag: 'CursorExpired',
      cursor: start.next,
    })
    expect(
      requestsTo(api, '/changes').some((r) => r.query.pageToken !== undefined),
    ).toBe(true)
  })

  it('is CursorExpired for a cursor it never handed out', async () => {
    const { source } = subject()
    expect(await failureTag(source.changes('not-a-cursor'))).toMatchObject({
      _tag: 'CursorExpired',
    })
  })
})

