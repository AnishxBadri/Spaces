/** The brand's name, for a mark's label and a monogram's letter. */
const BRAND_NAME: Record<Brand, string> = {
  google: 'Google',
  box: 'Box',
  airtable: 'Airtable',
  gmail: 'Gmail',
  apollo: 'Apollo',
  exa: 'Exa',
  granola: 'Granola',
  anthropic: 'Anthropic',
  openai: 'OpenAI',
  googleCalendar: 'Google Calendar',
  googleDrive: 'Google Drive',
}

const BY_NAME = new Map(
  Object.entries(BRAND_NAME).map(([brand, name]) => [
    name.toLowerCase().replace(/[^a-z]/g, ''),
    brand,
  ]),
)

const isBrand = (s: string | undefined): s is Brand =>
  s !== undefined && s in BRAND_NAME

/**
 * The brand a name means — `Granola`, `google-drive`, `Apollo.io` — or null
 * for a plugin with no mark of its own.
 */
export function brandOf(name: string): Brand | null {
  const key = name
    .toLowerCase()
    .replace(/\.io$/, '')
    .replace(/[^a-z]/g, '')
  const hit = BY_NAME.get(key)
  return isBrand(hit) ? hit : null
}

export function ProviderMark({
  brand,
  className,
}: {
  brand: Brand
  className?: string | undefined
}) {
  const d = PATH[brand]
  return (
    <svg
      role="img"
      aria-label={BRAND_NAME[brand]}
      data-provider-mark={brand}
      viewBox="0 0 24 24"
      fill="currentColor"
      className={cn('size-4 shrink-0', className)}
    >
      {d === undefined ? (
        <>
          <path
            fill="none"
            stroke="currentColor"
            strokeWidth={1.5}
            d="M2.75 2.75h18.5v18.5H2.75z"
          />
          <text
            x="12"
            y="16.25"
            textAnchor="middle"
            fontFamily="var(--font-mono)"
            fontSize="12"
            fontWeight="600"
          >
            {BRAND_NAME[brand].charAt(0)}
          </text>
        </>
      ) : (
        <path d={d} />
      )}
    </svg>
  )
}
